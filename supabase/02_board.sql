-- 24 小時看板:四種日子類型 x 六條軌道 x 48 個半小時格
-- wk 平日(Benny 返工) / off Benny 休假日 / sat 週六 / sun 週日·公假
create table if not exists public.board_slots (
  id bigserial primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  day_type text not null check (day_type in ('wk','off','sat','sun')),
  track text not null,
  slot int not null check (slot between 0 and 47),
  task text not null default '',
  unique (user_id, day_type, track, slot)
);
alter table public.board_slots enable row level security;
drop policy if exists board_owner on public.board_slots;
create policy board_owner on public.board_slots for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

